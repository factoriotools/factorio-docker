"""Offline regression checks for the Azure deployment template.

These protect deployment wiring; Azure provisioning and multiplayer still need
validation in the target subscription.
"""

import json
from pathlib import Path
import unittest
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "configs/Azure/CreateContainer.json"
STORAGE_TYPE = "Microsoft.Storage/storageAccounts"
SHARE_TYPE = STORAGE_TYPE + "/fileServices/shares"
GROUP_TYPE = "Microsoft.ContainerInstance/containerGroups"
STORAGE_ID = "resourceId('Microsoft.Storage/storageAccounts', parameters('storageAccountName'))"
SHARE_ID = "resourceId('Microsoft.Storage/storageAccounts/fileServices/shares', parameters('storageAccountName'), 'default', variables('fileShareName'))"
GROUP_ID = "resourceId('Microsoft.ContainerInstance/containerGroups', parameters('containerGroupsName'))"


def unique_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


class AzureTemplateTests(unittest.TestCase):
    def setUp(self):
        self.template = json.loads(TEMPLATE.read_text(), object_pairs_hook=unique_keys)
        self.resources = {resource["type"]: resource for resource in self.template["resources"]}
        self.storage = self.resources[STORAGE_TYPE]
        self.share = self.resources[SHARE_TYPE]
        self.group = self.resources[GROUP_TYPE]
        self.container = self.group["properties"]["containers"][0]["properties"]

    def test_complete_dependency_chain(self):
        self.assertEqual(set(self.resources), {STORAGE_TYPE, SHARE_TYPE, GROUP_TYPE})
        self.assertEqual(len(self.template["resources"]), 3)
        self.assertIn(f"[{STORAGE_ID}]", self.share["dependsOn"])
        self.assertIn(f"[{SHARE_ID}]", self.group["dependsOn"])
        self.assertEqual(self.share["name"], "[concat(parameters('storageAccountName'), '/default/', variables('fileShareName'))]")
        self.assertEqual(self.storage["name"], "[parameters('storageAccountName')]")
        self.assertEqual(self.group["name"], "[parameters('containerGroupsName')]")

    def test_generated_names_are_stable_and_scoped(self):
        parameters = self.template["parameters"]
        for name in ("storageAccountName", "dnsPrefix"):
            with self.subTest(parameter=name):
                default = parameters[name]["defaultValue"]
                self.assertIn("uniqueString(resourceGroup().id, parameters('containerGroupsName'))", default)
                self.assertNotIn("newGuid", default)
                self.assertNotIn("utcNow", default)
                self.assertNotIn("<", default)
        self.assertEqual(parameters["storageAccountName"]["minLength"], 3)
        self.assertEqual(parameters["storageAccountName"]["maxLength"], 24)
        self.assertLessEqual(parameters["dnsPrefix"]["maxLength"], 63)

    def test_public_ip_is_assigned_and_dns_reuse_is_scoped(self):
        address = self.group["properties"]["ipAddress"]
        self.assertNotIn("ip", address)
        self.assertEqual(address["type"], "Public")
        self.assertEqual(address["dnsNameLabel"], "[parameters('dnsPrefix')]")
        self.assertEqual(address["autoGeneratedDomainNameLabelScope"], "ResourceGroupReuse")
        output = self.template["outputs"]["serverAddress"]["value"]
        self.assertIn(f"reference({GROUP_ID}, '{self.group['apiVersion']}').ipAddress.fqdn", output)
        self.assertIn(":34197", output)

    def test_only_game_udp_port_is_published(self):
        expected = [{"protocol": "UDP", "port": 34197}]
        self.assertEqual(self.group["properties"]["ipAddress"]["ports"], expected)
        self.assertEqual(self.container["ports"], expected)

    def test_persistent_share_is_mounted_at_factorio(self):
        volumes = self.group["properties"]["volumes"]
        self.assertEqual(len(volumes), 1)
        volume = volumes[0]
        self.assertEqual(self.container["volumeMounts"], [
            {"name": volume["name"], "readOnly": False, "mountPath": "/factorio"}
        ])
        share = volume["azureFile"]
        self.assertFalse(share["readOnly"])
        self.assertEqual(share["shareName"], "[variables('fileShareName')]")
        self.assertEqual(share["storageAccountName"], "[parameters('storageAccountName')]")
        self.assertEqual(self.share["properties"]["enabledProtocols"], "SMB")
        self.assertEqual(self.template["variables"]["fileShareName"], "factorio")

    def test_keys_are_looked_up_and_not_output(self):
        key = self.group["properties"]["volumes"][0]["azureFile"]["storageAccountKey"]
        self.assertEqual(key, f"[listKeys({STORAGE_ID}, '{self.storage['apiVersion']}').keys[0].value]")
        outputs = json.dumps(self.template["outputs"]).lower()
        for secret in ("listkeys", "storageaccountkey", "password", "token"):
            self.assertNotIn(secret, outputs)
        self.assertEqual(self.template["outputs"]["storageAccountName"]["value"], "[parameters('storageAccountName')]")

    def test_storage_security_defaults(self):
        props = self.storage["properties"]
        self.assertEqual(props["minimumTlsVersion"], "TLS1_2")
        self.assertTrue(props["supportsHttpsTrafficOnly"])
        self.assertFalse(props["allowBlobPublicAccess"])
        self.assertEqual(self.storage["kind"], "StorageV2")

    def test_linux_root_compatibility_without_privileged_container(self):
        self.assertEqual(self.group["properties"]["osType"], "Linux")
        env = {item["name"]: item["value"] for item in self.container["environmentVariables"]}
        self.assertEqual(env["PUID"], "0")
        self.assertEqual(env["PGID"], "0")
        self.assertFalse(self.container.get("securityContext", {}).get("privileged", False))
        self.assertEqual(self.container["image"], "[concat('factoriotools/factorio:', parameters('factorioVersion'))]")
        self.assertEqual(self.template["parameters"]["factorioVersion"]["defaultValue"], "stable")
        self.assertNotIn("command", self.container, "Keep the image's normal entrypoint")

    def test_compute_requests_are_bounded_parameters(self):
        requests = self.container["resources"]["requests"]
        self.assertEqual(requests["cpu"], "[parameters('cpuCores')]")
        self.assertEqual(requests["memoryInGB"], "[parameters('memoryInGb')]")
        for name, maximum in (("cpuCores", 31), ("memoryInGb", 240)):
            parameter = self.template["parameters"][name]
            self.assertEqual(parameter["type"], "int")
            self.assertGreaterEqual(parameter["minValue"], 1)
            self.assertLessEqual(parameter["maxValue"], maximum)
            self.assertTrue(parameter["minValue"] <= parameter["defaultValue"] <= parameter["maxValue"])

    def test_deployment_guide_and_portal_button(self):
        guide = (TEMPLATE.parent / "README.md").read_text()
        decoded = unquote(guide)
        self.assertIn("https://raw.githubusercontent.com/factoriotools/factorio-docker/master/configs/Azure/CreateContainer.json", decoded)
        self.assertIn("--mode Incremental", guide)
        self.assertNotIn("--mode Complete", guide)
        self.assertIn("PUID=0", guide)
        self.assertIn("PGID=0", guide)
        self.assertIn("not proof", guide)
        self.assertIn("configs/Azure/README.md", (ROOT / "README.md").read_text())


if __name__ == "__main__":
    unittest.main()
